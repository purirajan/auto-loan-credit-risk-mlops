"""Generate PSI and delayed-outcome calibration monitoring reports."""

import argparse
import json
from datetime import datetime
from pathlib import Path

import pandas as pd

from configs.settings import ARTIFACTS_DIR, OUTPUT_DIR
from src.evaluation.monitoring import calculate_monitoring_report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--scored-csv",
        type=Path,
        default=OUTPUT_DIR / "scored_applications.csv",
        help="Scored applications CSV, with default_flag added after outcomes mature for calibration metrics.",
    )
    parser.add_argument(
        "--profile-json",
        type=Path,
        default=ARTIFACTS_DIR / "monitoring_profile.json",
        help="Training feature-distribution profile generated by model training.",
    )
    parser.add_argument(
        "--output-json",
        type=Path,
        default=OUTPUT_DIR / "monitoring_report.json",
        help="Destination monitoring report JSON.",
    )
    args = parser.parse_args()

    scored = pd.read_csv(args.scored_csv)
    profile = json.loads(args.profile_json.read_text())
    report = calculate_monitoring_report(scored, profile)
    report["checked_at"] = datetime.now().isoformat(timespec="seconds")
    report["model_version"] = (
        str(scored["model_version"].iloc[0]) if "model_version" in scored else "unknown"
    )
    args.output_json.parent.mkdir(parents=True, exist_ok=True)
    args.output_json.write_text(json.dumps(report, indent=2))

    for warning in report["warnings"]:
        print(f"WARNING: {warning}")
    for alert in report["alerts"]:
        print(f"ALERT: {alert}")
    print(f"Monitoring report saved to {args.output_json}")
    if report["retraining_recommended"]:
        print("Review this population for retraining; no automatic retraining was triggered.")


if __name__ == "__main__":
    main()
